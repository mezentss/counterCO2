def search_cities(query: str, limit: int = 10) -> list:
    """
    Поиск городов по частичному совпадению названия.
    
    Args:
        query: Поисковый запрос
        limit: Максимальное количество результатов
        
    Returns:
        Список найденных городов с информацией
    """
    if not query:
        return []
    
    query_lower = query.lower()
    results = []
    
    # Поиск в основной базе данных
    for city_name, (lat, lon, country) in CITIES_DB.items():
        if query_lower in city_name.lower():
            results.append({
                'name': city_name,
                'country': country,
                'coordinates': (lat, lon),
                'display_name': f"{city_name}, {country}"
            })
    
    # Поиск в алиасах
    for alias, real_name in CITY_ALIASES.items():
        if query_lower in alias.lower() and real_name in CITIES_DB:
            lat, lon, country = CITIES_DB[real_name]
            result = {
                'name': real_name,
                'country': country,
                'coordinates': (lat, lon),
                'display_name': f"{real_name}, {country}"
            }
            if result not in results:
                results.append(result)
    
    # Сортируем по релевантности (точные совпадения в начале)
    def relevance_score(item):
        name_lower = item['name'].lower()
        if name_lower == query_lower:
            return 0  # Точное совпадение
        elif name_lower.startswith(query_lower):
            return 1  # Начинается с запроса
        else:
            return 2  # Содержит запрос
    
    results.sort(key=relevance_score)
    return results[:limit]


def get_city_info(city_name: str) -> dict:
    """
    Получение информации о городе по названию.
    
    Args:
        city_name: Название города
        
    Returns:
        Словарь с информацией о городе или None если не найден
    """
    # Проверяем основную базу
    if city_name in CITIES_DB:
        lat, lon, country = CITIES_DB[city_name]
        return {
            'name': city_name,
            'country': country,
            'coordinates': (lat, lon),
            'display_name': f"{city_name}, {country}"
        }
    
    # Проверяем алиасы
    if city_name in CITY_ALIASES:
        real_name = CITY_ALIASES[city_name]
        return get_city_info(real_name)
    
    return None


def get_all_cities() -> list:
    """
    Получение списка всех городов в базе данных.
    
    Returns:
        Список всех городов с информацией
    """
    cities = []
    for city_name, (lat, lon, country) in CITIES_DB.items():
        cities.append({
            'name': city_name,
            'country': country,
            'coordinates': (lat, lon),
            'display_name': f"{city_name}, {country}"
        })
    
    return sorted(cities, key=lambda x: x['name'])


